// Skema PostgreSQL (Supabase). Idempoten: aman dijalankan berulang kali.
// Waktu disimpan sebagai teks UTC 'YYYY-MM-DD HH:MM:SS' (format yang dipakai seluruh tampilan & CSV).
export const SCHEMA = `
CREATE OR REPLACE FUNCTION utc_now() RETURNS text LANGUAGE sql STABLE AS
  $$ SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE TABLE IF NOT EXISTS brands (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  color text NOT NULL DEFAULT '#0f766e',
  logo text,
  cover text,
  style text NOT NULL DEFAULT '{}',
  created_at text NOT NULL DEFAULT utc_now()
);
CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('admin','brand')),
  brand_id integer REFERENCES brands(id) ON DELETE CASCADE,
  created_at text NOT NULL DEFAULT utc_now()
);
CREATE TABLE IF NOT EXISTS forms (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES brands(id) ON DELETE CASCADE,
  slug text NOT NULL UNIQUE,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  thank_you text NOT NULL DEFAULT 'Terima kasih, jawaban kamu sudah kami terima.',
  questions text NOT NULL DEFAULT '[]',
  is_active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL DEFAULT utc_now(),
  updated_at text NOT NULL DEFAULT utc_now()
);
CREATE TABLE IF NOT EXISTS responses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_id integer NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
  answers text NOT NULL,
  track_token text UNIQUE,
  created_at text NOT NULL DEFAULT utc_now()
);
CREATE TABLE IF NOT EXISTS files (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  response_id integer NOT NULL REFERENCES responses(id) ON DELETE CASCADE,
  name text NOT NULL,
  mime text NOT NULL,
  data bytea NOT NULL
);
CREATE TABLE IF NOT EXISTS shipments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  response_id integer NOT NULL UNIQUE REFERENCES responses(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending',
  items text NOT NULL DEFAULT '',
  courier text NOT NULL DEFAULT '',
  tracking_no text NOT NULL DEFAULT '',
  updated_at text NOT NULL DEFAULT utc_now()
);
CREATE TABLE IF NOT EXISTS shipment_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id integer NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
  status text NOT NULL,
  note text NOT NULL DEFAULT '',
  is_public integer NOT NULL DEFAULT 0,
  courier text NOT NULL DEFAULT '',
  tracking_no text NOT NULL DEFAULT '',
  actor text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT utc_now()
);
-- google_sub: id akun Google yang terkunci ke user ini (diisi saat login Google pertama).
ALTER TABLE users ADD COLUMN IF NOT EXISTS google_sub text;

-- invite_token: kode link undangan /undangan/<token>; siapa pun yang login Google lewat link ini
-- menjadi anggota brand tersebut. Diganti untuk mencabut link lama.
ALTER TABLE brands ADD COLUMN IF NOT EXISTS invite_token text;
ALTER TABLE brands ALTER COLUMN invite_token SET DEFAULT replace(gen_random_uuid()::text, '-', '');
UPDATE brands SET invite_token = replace(gen_random_uuid()::text, '-', '') WHERE invite_token IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS brands_invite_token ON brands(invite_token);

-- Personalisasi aplikasi oleh admin: app_name, tagline, logo (data URL), primary (#rrggbb).
CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE INDEX IF NOT EXISTS forms_brand_id ON forms(brand_id);
CREATE INDEX IF NOT EXISTS responses_form_id ON responses(form_id);
CREATE INDEX IF NOT EXISTS files_response_id ON files(response_id);
CREATE INDEX IF NOT EXISTS shipment_events_shipment_id ON shipment_events(shipment_id);

-- Supabase membuka tabel schema public lewat REST API (kunci anon bersifat publik).
-- RLS tanpa policy menutup akses itu; aplikasi terhubung sebagai role postgres yang melewati RLS.
ALTER TABLE brands ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE forms ENABLE ROW LEVEL SECURITY;
ALTER TABLE responses ENABLE ROW LEVEL SECURITY;
ALTER TABLE files ENABLE ROW LEVEL SECURITY;
ALTER TABLE shipments ENABLE ROW LEVEL SECURITY;
ALTER TABLE shipment_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
`;
